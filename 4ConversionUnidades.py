#Conversion Unidades Temperatura
celsius = float(input("ingrese la temperatura en grados Celsius: "))
fahrenheit = (celsius * 9/5) + 32
Kelvin = celsius + 273.15
print("La temperatura en grados Fahrenheit es:", fahrenheit)
print("La temperatura en grados Kelvin es:", Kelvin)

#Conversion unidades de Longitud
Kilometros = float(input("Ingrese la distancia en kilómetros: "))
Millas = Kilometros * 0.621371
print("La distancia en millas es:", Millas)

#conversion Peso
kilogramos = float(input("Ingrese el peso en kilogramos: "))
libras = kilogramos * 2.20462
print("El peso en libras es:", libras)

#Conversion Moneda
Dolar = float(input("Ingrese la cantidad de dolares que tiene: "))
PesoColombiano = Dolar * 3500
print("La cantidad de pesos colombianos es:", PesoColombiano)

